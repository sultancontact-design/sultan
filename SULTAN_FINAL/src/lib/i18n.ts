export const langMeta: Record<SupportedLang, { name: string; dir: 'rtl' | 'ltr'; flag: string }> = {
  ar:    { name: 'العربية',    dir: 'rtl', flag: '🇲🇦' },
  fr:    { name: 'Français',   dir: 'ltr', flag: '🇫🇷' },
  en:    { name: 'English',    dir: 'ltr', flag: '🇬🇧' },
  darija: { name: 'الدارجة',   dir: 'rtl', flag: '🇲🇦' },
};

// ═══════════════════════════════════════════
//  Translation function (hook-compatible)
// ═══════════════════════════════════════════

/**
 * Get a translated string by key and language.
 * Falls back: requested lang → 'ar' → key itself.
 *
 * @param key  - The translation key (e.g. 'heroTitle')
 * @param lang - The target language code ('ar' | 'fr' | 'en' | 'darija')
 * @returns The translated string, or the key if not found
 */
export function t(key: string, lang: SupportedLang = 'ar'): string {
  // Try the requested language first
  if (translations[lang]?.[key]) {
    return translations[lang][key];
  }
  // Fallback to Arabic (primary language)
  if (translations.ar?.[key]) {
    return translations.ar[key];
  }
  // Ultimate fallback: return the key itself so nothing breaks
  return key;
}

/**
 * React hook-compatible translation function factory.
 * Returns a bound `t` function for a given language.
 * Usage in components:
 *   const t = useTranslation('fr');
 *   <h1>{t('heroTitle')}</h1>
 */
export function useTranslation(lang: SupportedLang = 'ar'): (key: string) => string {
  return (key: string) => t(key, lang);
}

/**
 * Check if a language is RTL.
 */
export function isRTL(lang: SupportedLang): boolean {
  return langMeta[lang]?.dir === 'rtl';
}

/**
 * Get all supported language codes.
 */
export function getSupportedLanguages(): SupportedLang[] {
  return Object.keys(translations) as SupportedLang[];
}

/**
 * Get the total number of translation keys per language.
 */
export function getTranslationCount(lang: SupportedLang): number {
  return Object.keys(translations[lang] || {}).length;
}
